"""Task 1 baseline: link/time-of-week historical mean.

The baseline uses only public-train observations and evaluates on public
validation. It is deliberately simple and deterministic. R1/R2/R3 masks are
generated by a stable hash so the reported lower bound is reproducible without
storing a separate mask file.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd


HERE = Path(__file__).resolve().parent.parent.parent
DEFAULT_RELEASE = HERE / "data_public" / "kaggle_release"
REGIMES = {"R1": 0.20, "R2": 0.30, "R3": 0.50}
SPEED_NORMALIZER = 25.0
FLOW_NORMALIZER = 600.0
SPEED_WEIGHT = 0.54
FLOW_WEIGHT = 0.46


def files(panel_dir: Path, split: str) -> list[Path]:
    return sorted((panel_dir / split / "mainline_states").glob("**/*.parquet"))


def slot_values(frame: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]:
    ts = pd.to_datetime(frame["timestamp"], utc=True)
    weekday = ts.dt.weekday.to_numpy(dtype=np.int16)
    tod = (ts.dt.hour * 12 + ts.dt.minute // 5).to_numpy(dtype=np.int16)
    return weekday, tod


def stable_mask(panel: str, regime: str, dates: pd.Series, timestamps: pd.Series, links: pd.Series) -> np.ndarray:
    rate = REGIMES[regime]
    values = (panel + "|" + regime + "|" + dates.astype(str) + "|" + timestamps.astype(str) + "|" + links.astype(str)).to_numpy()
    return np.fromiter(
        (
            int.from_bytes(hashlib.blake2b(value.encode("utf-8"), digest_size=8).digest(), "big") / 2**64 < rate
            for value in values
        ),
        dtype=bool,
        count=len(values),
    )


def build_profile(panel: str, panel_dir: Path) -> tuple[dict, dict, dict]:
    train_files = files(panel_dir, "train")
    if not train_files:
        raise ValueError(f"{panel}: no public train partitions")
    first = pd.read_parquet(train_files[0], columns=["link_id"])
    link_ids = sorted(first.link_id.astype(str).unique())
    link_index = {link_id: i for i, link_id in enumerate(link_ids)}
    n_links = len(link_ids)
    n_slots = 7 * 288
    speed_sum = np.zeros((n_links, n_slots), dtype=np.float64)
    speed_count = np.zeros((n_links, n_slots), dtype=np.int64)
    flow_sum = np.zeros((n_links, n_slots), dtype=np.float64)
    flow_count = np.zeros((n_links, n_slots), dtype=np.int64)
    for i, path in enumerate(train_files, 1):
        frame = pd.read_parquet(
            path,
            columns=["timestamp", "link_id", "speed_kmh", "flow_vph", "pct_observed"],
        )
        frame["link_id"] = frame["link_id"].astype(str)
        li = frame.link_id.map(link_index).to_numpy(dtype=np.int64)
        weekday, tod = slot_values(frame)
        slot = weekday * 288 + tod
        # Contract rule: only cells with at least 75% observed measurements
        # and finite required channels contribute to a training profile.
        valid = (
            pd.to_numeric(frame.pct_observed, errors="coerce").ge(75)
            & frame.speed_kmh.notna()
            & frame.flow_vph.notna()
        ).to_numpy()
        sp = pd.to_numeric(frame.speed_kmh, errors="coerce").to_numpy(dtype=float)
        fl = pd.to_numeric(frame.flow_vph, errors="coerce").to_numpy(dtype=float)
        valid_sp = valid & np.isfinite(sp)
        valid_fl = valid & np.isfinite(fl)
        np.add.at(speed_sum, (li[valid_sp], slot[valid_sp]), sp[valid_sp])
        np.add.at(speed_count, (li[valid_sp], slot[valid_sp]), 1)
        np.add.at(flow_sum, (li[valid_fl], slot[valid_fl]), fl[valid_fl])
        np.add.at(flow_count, (li[valid_fl], slot[valid_fl]), 1)
        if i % 50 == 0:
            print(f"[{panel}] profile files {i}/{len(train_files)}", flush=True)
    speed_mean = np.zeros_like(speed_sum)
    flow_mean = np.zeros_like(flow_sum)
    np.divide(speed_sum, np.maximum(speed_count, 1), out=speed_mean, where=speed_count > 0)
    np.divide(flow_sum, np.maximum(flow_count, 1), out=flow_mean, where=flow_count > 0)
    # Link-wide fallback if a specific weekday/time slot has no observations.
    speed_link = np.divide(speed_sum.sum(axis=1), np.maximum(speed_count.sum(axis=1), 1))
    flow_link = np.divide(flow_sum.sum(axis=1), np.maximum(flow_count.sum(axis=1), 1))
    return (
        {"link_ids": link_ids, "link_index": link_index, "mean": speed_mean, "fallback": speed_link},
        {"link_ids": link_ids, "link_index": link_index, "mean": flow_mean, "fallback": flow_link},
        {"speed_count": speed_count, "flow_count": flow_count},
    )


def evaluate_panel(panel: str, release: Path, output_root: Path) -> list[dict]:
    panel_dir = release / "corridors" / panel
    speed_profile, flow_profile, counts = build_profile(panel, panel_dir)
    link_index = speed_profile["link_index"]
    predictions = []
    sums = {r: {"speed_sq": 0.0, "flow_sq": 0.0, "n": 0} for r in REGIMES}
    for i, path in enumerate(files(panel_dir, "validation"), 1):
        frame = pd.read_parquet(
            path,
            columns=["date", "timestamp", "link_id", "speed_kmh", "flow_vph", "is_score_eligible"],
        )
        frame["link_id"] = frame["link_id"].astype(str)
        li = frame.link_id.map(link_index).to_numpy(dtype=np.int64)
        weekday, tod = slot_values(frame)
        slot = weekday * 288 + tod
        pred_speed = speed_profile["mean"][li, slot]
        pred_flow = flow_profile["mean"][li, slot]
        no_speed = counts["speed_count"][li, slot] == 0
        no_flow = counts["flow_count"][li, slot] == 0
        pred_speed = np.where(no_speed, speed_profile["fallback"][li], pred_speed)
        pred_flow = np.where(no_flow, flow_profile["fallback"][li], pred_flow)
        frame["pred_speed_kmh"] = pred_speed
        frame["pred_flow_vph"] = pred_flow
        predictions.append(frame)
        valid = frame.is_score_eligible.astype(bool).to_numpy().copy()
        true_speed = pd.to_numeric(frame.speed_kmh, errors="coerce").to_numpy(dtype=float)
        true_flow = pd.to_numeric(frame.flow_vph, errors="coerce").to_numpy(dtype=float)
        valid &= np.isfinite(true_speed) & np.isfinite(true_flow) & np.isfinite(pred_speed) & np.isfinite(pred_flow)
        dates = frame.date if "date" in frame else frame.timestamp.astype(str).str[:10]
        for regime in REGIMES:
            mask = valid & stable_mask(panel, regime, dates, frame.timestamp, frame.link_id)
            ds = pred_speed[mask] - true_speed[mask]
            dq = pred_flow[mask] - true_flow[mask]
            sums[regime]["speed_sq"] += float(np.sum(ds * ds))
            sums[regime]["flow_sq"] += float(np.sum(dq * dq))
            sums[regime]["n"] += int(mask.sum())
    pred_dir = output_root / panel
    pred_dir.mkdir(parents=True, exist_ok=True)
    pd.concat(predictions, ignore_index=True).to_parquet(pred_dir / "validation_predictions.parquet", index=False)
    rows = []
    for regime, s in sums.items():
        n = max(s["n"], 1)
        rmse_speed = float(np.sqrt(s["speed_sq"] / n))
        rmse_flow = float(np.sqrt(s["flow_sq"] / n))
        speed_score = max(0.0, 1.0 - rmse_speed / SPEED_NORMALIZER)
        flow_score = max(0.0, 1.0 - rmse_flow / FLOW_NORMALIZER)
        state_score = SPEED_WEIGHT * speed_score + FLOW_WEIGHT * flow_score
        rows.append(
            {
                "panel": panel,
                "regime": regime,
                "n_cells": s["n"],
                "rmse_speed_kmh": rmse_speed,
                "rmse_flow_vph": rmse_flow,
                "S_speed": speed_score,
                "S_flow": flow_score,
                "S_state_regime": state_score,
            }
        )
    rows.append(
        {
            "panel": panel,
            "regime": "macro_mean",
            "n_cells": sum(s["n"] for s in sums.values()),
            "rmse_speed_kmh": np.nan,
            "rmse_flow_vph": np.nan,
            "S_speed": np.nan,
            "S_flow": np.nan,
            "S_state_regime": float(np.mean([r["S_state_regime"] for r in rows])),
        }
    )
    return rows


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--release-root", type=Path, default=DEFAULT_RELEASE)
    ap.add_argument("--panel", action="append")
    ap.add_argument("--output-root", type=Path, default=HERE / "baselines" / "task1_historical_mean")
    args = ap.parse_args()
    manifest = json.loads((HERE / "config" / "corridors.json").read_text(encoding="utf-8"))
    panels = [p["corridor_id"] for p in manifest["panels"]]
    selected = [p for p in panels if not args.panel or p in set(args.panel)]
    rows = []
    for panel in selected:
        print(f"[Task1 baseline] {panel}", flush=True)
        rows.extend(evaluate_panel(panel, args.release_root.resolve(), args.output_root.resolve()))
    report = HERE / "reports" / "baseline_task1_historical_mean.csv"
    report.parent.mkdir(exist_ok=True)
    pd.DataFrame(rows).to_csv(report, index=False)
    print(f"Wrote {report}")


if __name__ == "__main__":
    main()
